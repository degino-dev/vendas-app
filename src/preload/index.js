  listarCidades: () => ipcRenderer.invoke('cidades:listar'),
  consultarCnpj: (cnpj) => ipcRenderer.invoke('cnpj:consultar', cnpj),
  listarBackups: () => ipcRenderer.invoke('backup:listar'),
  criarBackup: () => ipcRenderer.invoke('backup:criar'),
  listarBackupsVendedor: (id) => ipcRenderer.invoke('backup:listarVendedor', id),
  listarBackupsGerais: () => ipcRenderer.invoke('backup:listarGerais'),
  restaurarBackupVendedor: (id, nome) => ipcRenderer.invoke('backup:restaurarVendedor', { id, nome }),
  restaurarBackupGeral: (nome) => ipcRenderer.invoke('backup:restaurarGeral', nome),
  carregarConfigBackup: () => ipcRenderer.invoke('backup:configCarregar'),
  salvarConfigBackup: (config) => ipcRenderer.invoke('backup:configSalvar', config),
  alterarCaminho: (novoCaminho) => ipcRenderer.invoke('config:alterarCaminho', novoCaminho),
